#: The one :class:`EmitterConfig` field that does **not** affect output. It changes
#: :attr:`castiron.emitters.EmittedFile.path`, never ``.content`` — determinism axis A8 asserts
#: exactly that, which is what licenses excluding it from the sweep.
NON_OUTPUT_AFFECTING_FIELD = 'output_filename'

#: A *source* option that affects output but is not an :class:`EmitterConfig` field, so the sweep
#: is 7 axes rather than 6.
SOURCE_AXIS = 'infer_generated_primary_keys'

#: The command that rewrites every committed golden. Quoted in every failure message, because a
#: failure a reader cannot act on is a failure that gets worked around.
REGENERATE_COMMAND = 'uv run python -m tests.unit.corpus.regenerate'


def config_axes() -> tuple[str, ...]:
    """Return the output-affecting config axis names, sorted.

    Derived from :func:`dataclasses.fields` rather than a hand-maintained list, so adding a
    seventh :class:`EmitterConfig` toggle automatically widens the manifest sweep — and
    ``test_corpus_selfcheck.py`` fails until the manifests are regenerated to cover it. That is
    CI-072's "enumerate, do not sample" made structural instead of remembered.

    Returns:
        The 7 axis names in sorted order.
    """
    emitter_axes = {f.name for f in dataclasses.fields(EmitterConfig) if f.name != NON_OUTPUT_AFFECTING_FIELD}
    return tuple(sorted(emitter_axes | {SOURCE_AXIS}))


@dataclass(frozen=True)
class SourceOptions:
    """The output-affecting keyword options of :func:`build_schema_from_document`.

    ⚠ **Debt, recorded deliberately (spec §12).** This exists only because those keywords are
    not modelled anywhere in ``src/`` today. It holds **exactly** those two and must not grow
    into a general config object. When CI-010 introduces a real source-options type in ``src/``,
    this must be **replaced** by it, not kept alongside it — two shapes for one concept is the
    Hard Rule #6 violation this note exists to prevent.

    ``disable_model_prefix_protection`` appears here *and* on :class:`EmitterConfig` because the
    product genuinely takes it in both places: ``castiron.cli.gen`` passes one flag to
    ``build_schema_from_document`` and to ``EmitterConfig``. The corpus mirrors that wiring, and
    ``test_corpus_selfcheck.py`` asserts the two never disagree in a case.

    Attributes:
        infer_generated_primary_keys: Report a sole NOT NULL integer primary key as identity.
        disable_model_prefix_protection: Do not rename ``model_``-prefixed columns.
    """

    infer_generated_primary_keys: bool = False
    disable_model_prefix_protection: bool = False


@dataclass(frozen=True)
class Defect:
    """A known-wrong behaviour whose output reaches a committed golden.

    Attributes:
        row_id: The WORKPLAN row that owns the fix (e.g. ``'CI-075'``).
        summary: One line, in the row's own words.
        why_it_is_wrong: What correct output would look like instead. This is the field that
            makes the witness test's failure message actionable rather than merely loud.
    """

    row_id: str
    summary: str
    why_it_is_wrong: str


@dataclass(frozen=True)
class InputFamily:
    """One committed source document and its provenance record.

    Attributes:
        family_id: The stem shared by the case ids built from this input.
        input_path: The document on disk.
        provenance_path: The sibling ``*.provenance.json``, or ``None`` for the CI-005 fixture,
            which predates the corpus and lives under ``tests/unit/sources/openapi/``.
        schema: The schema the document describes (it never states its own name).
        origin: ``'captured'`` from a real PostgREST, or ``'synthetic'`` (hand-authored).
    """

    family_id: str
    input_path: Path
    provenance_path: Path | None
    schema: str
    origin: Literal['captured', 'synthetic']


@dataclass(frozen=True)
class CorpusCase:
    """One (input, config) point with committed goldens.

    Attributes:
        case_id: ``<input-family>-<config-name>``. One string, one meaning: the pytest
            parametrization id, the golden file stem, and the manifest header all use it.
        family: The input this case reads.
        source_options: What ``build_schema_from_document`` is called with.
        emitter_config: The **real** :class:`EmitterConfig` the emitter is constructed with.
        status: ``'asserted'`` ⇒ no known defect reaches these bytes. ``'characterized'`` ⇒ at
            least one does, and ``defects`` names every one.
        defects: WORKPLAN row ids, all keys of :data:`KNOWN_DEFECTS`.
        compiles: Whether the emitted module is expected to parse. Asserted **exactly**, so a
            ``False`` that becomes ``True`` goes red and names the row that must have been fixed.
        golden_module: The committed emitted module, or ``None`` for an IR-only case.
        golden_ir: The committed ``Schema.as_dict()`` golden.
    """

    case_id: str
    family: InputFamily
    source_options: SourceOptions
    emitter_config: EmitterConfig
    status: Literal['asserted', 'characterized']
    defects: tuple[str, ...]
    compiles: bool
    golden_module: Path | None
    golden_ir: Path

    @property
    def config_key(self) -> str:
        """The manifest row key for this case's config (see :func:`config_key`)."""
        return config_key(self.emitter_config, self.source_options)


def config_key(emitter_config: EmitterConfig, source_options: SourceOptions) -> str:
    """Render one point of the config space as a stable, total-ordered key.

    Full field names, never abbreviations: an abbreviation table is one more thing to rot, and
    the key is what a reviewer reads when a manifest row moves.

    Args:
        emitter_config: The emitter half of the config point.
        source_options: The source half.

    Returns:
        ``'add_null_parent_classes=0,disable_model_prefix_protection=0,...'``.
    """
    values: dict[str, bool] = {
        f.name: bool(getattr(emitter_config, f.name))
        for f in dataclasses.fields(EmitterConfig)
        if f.name != NON_OUTPUT_AFFECTING_FIELD
    }
    values[SOURCE_AXIS] = source_options.infer_generated_primary_keys
    return ','.join(f'{axis}={int(values[axis])}' for axis in config_axes())


def all_config_points() -> tuple[tuple[EmitterConfig, SourceOptions], ...]:
    """Return **every** reachable config point, ordered by :func:`config_key`.

    All 2**7 of them, not a sample. The measurement that forces this: 128 configs produce **96**
    distinct outputs on the ``testbed-public`` capture, so the axes *interact* — a corpus of
    single-flag-flip goldens provably cannot see an interaction, and a default-only corpus guards
    1 of 96 reachable outputs while ``check`` users run the other 95.

    Returns:
        128 ``(emitter_config, source_options)`` pairs in config-key order.
    """
    axes = config_axes()
    points: list[tuple[EmitterConfig, SourceOptions]] = []
    for bits in range(2 ** len(axes)):
        values = {axis: bool(bits >> index & 1) for index, axis in enumerate(axes)}
        source_options = SourceOptions(
            infer_generated_primary_keys=values[SOURCE_AXIS],
            # The CLI passes one flag to both halves; the corpus mirrors that wiring exactly.
            disable_model_prefix_protection=values['disable_model_prefix_protection'],
        )
        emitter_config = EmitterConfig(**{axis: values[axis] for axis in axes if axis != SOURCE_AXIS})
        points.append((emitter_config, source_options))
    return tuple(sorted(points, key=lambda point: config_key(*point)))


