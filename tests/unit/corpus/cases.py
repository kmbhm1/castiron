"""The corpus case table: inputs, configs, goldens, and the defects each golden encodes.

This module is **declarative**. It states what the corpus contains; every assertion about it
lives in a ``test_*.py`` sibling, and every artifact it names is regenerated by
``tests.unit.corpus.regenerate``.

Why a golden is not automatically an endorsement
------------------------------------------------
A golden is a several-thousand-line assertion that *current output is correct*. Some of
castiron's current output is **known wrong** — five open WORKPLAN rows produce bytes that reach
a committed golden. Left implicit, this corpus would quietly cement those bugs as the contract,
and the day one is fixed the cheapest response to the red test would be "regenerate the golden",
silently re-endorsing whatever replaced it.

So every known-wrong region is **named**: :data:`KNOWN_DEFECTS` carries one entry per WORKPLAN
row whose output reaches a golden, ``test_witnesses.py`` asserts each defect's evidence **is
present**, and each :class:`CorpusCase` declares ``status='characterized'`` plus the row ids it
carries. ``status='asserted'`` means the stronger thing: *no known defect reaches these bytes.*

Typing note (spec §12, Hard Rule #6): :attr:`CorpusCase.emitter_config` holds a **real**
:class:`castiron.emitters.EmitterConfig` — never six loose booleans, never a parallel dataclass.
The config axis names are derived from ``dataclasses.fields(EmitterConfig)`` at runtime, so a new
toggle widens the sweep automatically instead of silently escaping it.
"""

